// Dev helper (local only). Reads backend/.dev-accounts.json, written by the seed.
//   node scripts/dev-accounts.js md            -> writes backend/.dev-accounts.md (readable table; git-ignored)
//   node scripts/dev-accounts.js code officer  -> prints the current 6-digit authenticator code for that account key or e-mail
const fs = require('fs');
const path = require('path');
const { authenticator } = require('otplib');

const file = path.join(__dirname, '..', '.dev-accounts.json');
if (!fs.existsSync(file)) {
  console.error('No .dev-accounts.json yet. Run: npm run db:seed');
  process.exit(1);
}
const accounts = JSON.parse(fs.readFileSync(file, 'utf8')).accounts;
const [cmd, arg] = process.argv.slice(2);

if (cmd === 'md') {
  const order = ['superadmin', 'officer', 'coordinator', 'hr', 'student', 'admin'];
  const rows = Object.entries(accounts).sort((a, b) => order.indexOf(a[1].role) - order.indexOf(b[1].role));
  const lines = [
    '# Demo accounts (local development only)',
    '',
    'Generated by `npm run db:seed`. Do not commit or share. Passwords change every time the seed is re-run.',
    'Sign in with the e-mail and password, then enter a 6-digit code: run `node scripts/dev-code.js <key>` (or add the secret to an authenticator app).',
    '',
    '| Role | Key | E-mail | Password | Authenticator secret |',
    '|---|---|---|---|---|',
    ...rows.map(([k, v]) => `| ${v.role} | \`${k}\` | ${v.email} | \`${v.password}\` | \`${v.totp_secret}\` |`),
    '',
  ];
  fs.writeFileSync(path.join(__dirname, '..', '.dev-accounts.md'), lines.join('\n'));
  console.log('Wrote backend/.dev-accounts.md');
} else if (cmd === 'code') {
  const hit = Object.entries(accounts).find(([k, v]) => k === arg || v.email === arg);
  if (!hit) {
    console.error('Unknown account. Keys: ' + Object.keys(accounts).join(', '));
    process.exit(1);
  }
  const left = 30 - (Math.floor(Date.now() / 1000) % 30);
  console.log(`${hit[1].email}  code: ${authenticator.generate(hit[1].totp_secret)}  (valid for ~${left}s)`);
} else {
  console.error('Usage: node scripts/dev-accounts.js md | code <key-or-email>');
  process.exit(1);
}
